-- 来执行本脚本。如果连接串里的占位符没解析（例如忘设 DB_HOST）、
-- 或数据库不可达/口令错误，这一步会直接抛异常，让应用**启动失败**，
-- 而不是"启动成功但一查就崩"。
--
-- 这样生产环境就不会出现：
--   · 健康检查通过，但接口全部 500；
--   · 定时任务在后台静默刷 UnknownHostException。

